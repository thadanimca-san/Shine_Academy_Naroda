      ['a', 'ा'],
      ['e', 'े'],
      ['i', 'ि'],
      ['o', 'ो'],
      ['u', 'ु'],
    ];

    var result = w;
    for (final pair in replacements) {
      result = result.replaceAll(pair[0], pair[1]);
    }
    return result;
  }
